"""Shareable reports: Markdown and a self-contained HTML page for one report or a whole case.

Everything is for people outside the tool, so indicators are defanged and feed-derived text
is neutralised: escaped in HTML, shown as inline code in Markdown. The HTML has no script and
no external resource.
"""

from __future__ import annotations

import html

from verdikt.cache import CaseDetail
from verdikt.models import Report, SourceResult
from verdikt.notify.format import defang


def _code(text: str) -> str:
    """Markdown inline code that cannot break out of its span or the table cell."""
    flat = " ".join(text.split()).replace("`", "'").replace("|", "/")
    return f"`{flat}`" if flat else ""


def _when(report: Report) -> str:
    return report.created_at.strftime("%Y-%m-%d %H:%M UTC")


def _results_rows(report: Report) -> list[SourceResult]:
    return sorted(report.results, key=lambda r: r.source)


# --- Markdown ----------------------------------------------------------------------------


def report_markdown(report: Report, heading: int = 1) -> str:
    h = "#" * heading
    lines = [
        f"{h} {report.level.value.upper()}: {defang(report.ioc)} ({report.ioc_type.value})",
        "",
        f"- Confidence: **{report.confidence.value}** ({report.agreeing}/{report.total} sources agree)",
        f"- Checked: {_when(report)} in {report.duration_ms} ms",
        f"- Report id: {_code(report.id)}",
        "",
    ]
    if report.reasons:
        lines += [f"{h}# Why", ""] + [f"- {_code(r)}" for r in report.reasons] + [""]
    lines += [
        f"{h}# Sources",
        "",
        "| Source | Level | Role | Weight | Result | Rules that fired |",
        "|---|---|---|---|---|---|",
    ]
    for r in _results_rows(report):
        level = r.level.value if r.status.value == "ok" else r.status.value
        lines.append(
            f"| {r.source} | {level} | {r.role} | {r.weight} | {_code(r.summary)} | "
            f"{_code('; '.join(r.fired))} |"
        )
    if report.cves:
        lines += ["", f"{h}# Vulnerabilities on the host", ""]
        for c in report.cves:
            extra = ", ".join(
                x
                for x in (
                    "in CISA KEV" if c.kev else "",
                    "ransomware use" if c.ransomware else "",
                    f"EPSS {c.epss * 100:.1f}%" if c.epss is not None else "",
                )
                if x
            )
            lines.append(f"- {c.id}{': ' + extra if extra else ''}")
    if report.seen_before:
        lines += ["", f"{h}# Seen before", ""]
        for s in report.seen_before:
            shared = ", ".join(defang(v) for v in s.shared)
            lines.append(f"- {defang(s.ioc)}: {s.level.value} (shares {_code(shared)})")
    lines += ["", "_Indicators are defanged. Generated by verdikt._", ""]
    return "\n".join(lines)


def case_markdown(case: CaseDetail, reports: list[Report]) -> str:
    lines = [f"# Investigation: {_code(case.title)}", ""]
    if case.tags:
        lines += ["Tags: " + ", ".join(_code(t) for t in case.tags), ""]
    lines += [
        f"Opened {case.created_at:%Y-%m-%d}, updated {case.updated_at:%Y-%m-%d}; "
        f"{len(reports)} report(s).",
        "",
    ]
    if case.notes.strip():
        lines += ["## Notes", "", case.notes.strip(), ""]
    lines += [
        "## Indicators",
        "",
        "| Indicator | Type | Verdict | Confidence |",
        "|---|---|---|---|",
    ]
    for r in reports:
        lines.append(
            f"| {defang(r.ioc)} | {r.ioc_type.value} | {r.level.value} | {r.confidence.value} |"
        )
    lines += [""]
    for r in reports:
        lines += [report_markdown(r, heading=2)]
    return "\n".join(lines)


# --- HTML --------------------------------------------------------------------------------

_CSS = """
body{font:15px/1.5 system-ui,sans-serif;max-width:60rem;margin:2rem auto;padding:0 1rem;color:#111}
h1,h2,h3{line-height:1.25} table{border-collapse:collapse;width:100%;font-size:13px;margin:.5rem 0 1rem}
th,td{border:1px solid #ccc;padding:.3rem .5rem;text-align:left;vertical-align:top}
code,.mono{font-family:ui-monospace,Menlo,Consolas,monospace;font-size:12.5px}
.level{font-weight:700;text-transform:uppercase}.notes{white-space:pre-wrap;border-left:3px solid #999;padding-left:.8rem}
.tag{border:1px solid #999;padding:0 .35rem;margin-right:.3rem;font-size:12px}
footer{margin-top:2rem;color:#555;font-size:12px}
@media print{body{margin:0}}
"""


def _e(text: object) -> str:
    return html.escape(str(text), quote=True)


def _report_html(report: Report, tag: str = "h1") -> str:
    out = [
        f'<{tag}><span class="level">{_e(report.level.value)}</span>: '
        f'<span class="mono">{_e(defang(report.ioc))}</span> ({_e(report.ioc_type.value)})</{tag}>',
        f"<p>Confidence <strong>{_e(report.confidence.value)}</strong> "
        f"({report.agreeing}/{report.total} sources agree). Checked {_e(_when(report))}.</p>",
    ]
    if report.reasons:
        out.append(
            "<h3>Why</h3><ul>"
            + "".join(f'<li class="mono">{_e(r)}</li>' for r in report.reasons)
            + "</ul>"
        )
    out.append(
        "<h3>Sources</h3><table><tr><th>Source</th><th>Level</th><th>Role</th><th>Weight</th><th>Result</th><th>Rules that fired</th></tr>"
    )
    for r in _results_rows(report):
        level = r.level.value if r.status.value == "ok" else r.status.value
        out.append(
            f"<tr><td>{_e(r.source)}</td><td>{_e(level)}</td><td>{_e(r.role)}</td><td>{r.weight}</td>"
            f'<td class="mono">{_e(r.summary)}</td><td class="mono">{_e("; ".join(r.fired))}</td></tr>'
        )
    out.append("</table>")
    if report.cves:
        out.append("<h3>Vulnerabilities on the host</h3><ul>")
        for c in report.cves:
            bits = [
                b
                for b in (
                    "in CISA KEV" if c.kev else "",
                    f"EPSS {c.epss * 100:.1f}%" if c.epss is not None else "",
                )
                if b
            ]
            out.append(f'<li class="mono">{_e(c.id)} {_e(", ".join(bits))}</li>')
        out.append("</ul>")
    if report.seen_before:
        out.append("<h3>Seen before</h3><ul>")
        for s in report.seen_before:
            shared = ", ".join(defang(v) for v in s.shared)
            out.append(
                f'<li><span class="mono">{_e(defang(s.ioc))}</span>: {_e(s.level.value)} (shares <span class="mono">{_e(shared)}</span>)</li>'
            )
        out.append("</ul>")
    return "\n".join(out)


def _page(title: str, body: str) -> str:
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1">'
        "<meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\">"
        f"<title>{_e(title)}</title><style>{_CSS}</style></head><body>{body}"
        "<footer>Indicators are defanged. Generated by verdikt.</footer></body></html>"
    )


def report_html(report: Report) -> str:
    return _page(f"verdikt: {defang(report.ioc)}", _report_html(report))


def case_html(case: CaseDetail, reports: list[Report]) -> str:
    parts = [f"<h1>Investigation: {_e(case.title)}</h1>"]
    if case.tags:
        parts.append(
            "<p>" + "".join(f'<span class="tag">{_e(t)}</span>' for t in case.tags) + "</p>"
        )
    parts.append(
        f"<p>Opened {_e(f'{case.created_at:%Y-%m-%d}')}, updated {_e(f'{case.updated_at:%Y-%m-%d}')}; {len(reports)} report(s).</p>"
    )
    if case.notes.strip():
        parts.append(f'<h2>Notes</h2><div class="notes">{_e(case.notes.strip())}</div>')
    parts.append(
        "<h2>Indicators</h2><table><tr><th>Indicator</th><th>Type</th><th>Verdict</th><th>Confidence</th></tr>"
    )
    for r in reports:
        parts.append(
            f'<tr><td class="mono">{_e(defang(r.ioc))}</td><td>{_e(r.ioc_type.value)}</td>'
            f"<td>{_e(r.level.value)}</td><td>{_e(r.confidence.value)}</td></tr>"
        )
    parts.append("</table>")
    parts += [_report_html(r, "h2") for r in reports]
    return _page(f"verdikt investigation: {case.title}", "\n".join(parts))
